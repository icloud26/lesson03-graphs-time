import streamlit as st
import pandas as pd
import plotly.express as px


# --------------------------------------------------
# 페이지 설정
# --------------------------------------------------
st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide"
)

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.write(
    "1년 동안의 일별 박스오피스 데이터를 이용해 "
    "영화의 관객 수가 시간에 따라 어떻게 변했는지 살펴봅니다."
)


# --------------------------------------------------
# 데이터 불러오기
# --------------------------------------------------
@st.cache_data
def load_data():
    df = pd.read_csv("kobis_daily.csv")

    # 날짜를 실제 날짜 형식으로 변환
    df["날짜"] = pd.to_datetime(
        df["날짜"].astype(str),
        format="%Y%m%d"
    )

    # 숫자로 사용할 열 변환
    number_columns = [
        "순위",
        "일관객",
        "누적관객",
        "스크린수",
        "상영횟수"
    ]

    for col in number_columns:
        df[col] = pd.to_numeric(
            df[col],
            errors="coerce"
        )

    return df


df = load_data()


# ==================================================
# 1구역 : 영화별 날짜별 일관객 변화
# ==================================================
st.divider()

st.header("1. 영화별 날짜별 일관객 변화")

st.write(
    "영화를 선택하면 날짜에 따라 하루 관객 수가 "
    "어떻게 변했는지 확인할 수 있습니다."
)

movie_list = sorted(
    df["영화명"].dropna().unique()
)

selected_movie = st.selectbox(
    "영화를 선택하세요",
    movie_list
)

movie_df = df[
    df["영화명"] == selected_movie
].copy()

movie_df = movie_df.sort_values("날짜")


# --------------------------------------------------
# 1번 선 그래프
# --------------------------------------------------
fig1 = px.line(
    movie_df,
    x="날짜",
    y="일관객",
    markers=True,
    title=f"{selected_movie}의 날짜별 일관객 변화"
)

fig1.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "관객 수: %{y:,.0f}명"
        "<extra></extra>"
    )
)

fig1.update_layout(
    xaxis_title="날짜",
    yaxis_title="일관객 수",
    hovermode="x unified"
)

st.plotly_chart(
    fig1,
    use_container_width=True
)

st.markdown("#### 💡 이 그래프로 알 수 있는 것")

st.info(
    "여기에 그래프를 보고 알 수 있는 특징을 한 문장으로 작성합니다."
)


# ==================================================
# 2구역 : 일관객 합계 상위 5편 비교
# ==================================================
st.divider()

st.header("2. 일관객 합계 상위 5편의 관객 변화")

st.write(
    "이 기간 동안 일관객 수의 합계가 가장 큰 영화 5편을 골라 "
    "날짜별 관객 변화를 비교합니다."
)


# --------------------------------------------------
# 영화별 일관객 합계 계산
# --------------------------------------------------
movie_totals = (
    df.groupby("영화명", as_index=False)["일관객"]
    .sum()
    .sort_values("일관객", ascending=False)
)

top5_movies = movie_totals.head(5)["영화명"].tolist()


# 상위 5편의 데이터만 선택
top5_df = df[
    df["영화명"].isin(top5_movies)
].copy()

top5_df = top5_df.sort_values("날짜")


# --------------------------------------------------
# 2번 선 그래프
# --------------------------------------------------
fig2 = px.line(
    top5_df,
    x="날짜",
    y="일관객",
    color="영화명",
    title="일관객 합계 상위 5편의 날짜별 관객 변화"
)

fig2.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "관객 수: %{y:,.0f}명"
        "<extra></extra>"
    )
)

fig2.update_layout(
    xaxis_title="날짜",
    yaxis_title="일관객 수",
    legend_title="영화명",
    hovermode="x unified"
)

st.plotly_chart(
    fig2,
    use_container_width=True
)


# --------------------------------------------------
# 그래프 사용 안내
# --------------------------------------------------
st.caption(
    "그래프 오른쪽의 영화명을 클릭하면 해당 영화의 선을 "
    "끄거나 다시 켤 수 있습니다."
)


# --------------------------------------------------
# 그래프 해석
# --------------------------------------------------
st.markdown("#### 💡 이 그래프로 알 수 있는 것")

st.info(
    "여기에 다섯 영화의 관객 변화에서 알 수 있는 특징을 "
    "한 문장으로 작성합니다."
)


# ==================================================
# 3구역 : 날짜별 10위권 일관객 합계
# ==================================================
st.divider()

st.header("3. 날짜별 10위권 일관객 합계")

st.write(
    "날짜별로 박스오피스 10위권 영화의 일관객 수를 모두 더해 "
    "극장 관객이 많았던 날과 적었던 날을 살펴봅니다."
)


# --------------------------------------------------
# 날짜별 10위권 일관객 합계 계산
# --------------------------------------------------
daily_total = (
    df.groupby("날짜", as_index=False)["일관객"]
    .sum()
    .sort_values("날짜")
)


# --------------------------------------------------
# 관객 합계가 가장 큰 날짜 3일 찾기
# --------------------------------------------------
top3_days = (
    daily_total
    .nlargest(3, "일관객")
    .sort_values("날짜")
)


# --------------------------------------------------
# 영역 그래프
# --------------------------------------------------
fig3 = px.area(
    daily_total,
    x="날짜",
    y="일관객",
    title="날짜별 박스오피스 10위권 일관객 합계"
)

fig3.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "10위권 관객 합계: %{y:,.0f}명"
        "<extra></extra>"
    )
)


# --------------------------------------------------
# 관객 합계가 가장 큰 3일 표시
# --------------------------------------------------
fig3.add_scatter(
    x=top3_days["날짜"],
    y=top3_days["일관객"],
    mode="markers+text",
    text=top3_days["날짜"].dt.strftime("%Y-%m-%d"),
    textposition="top center",
    marker=dict(size=10),
    name="관객이 가장 많았던 3일",
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "10위권 관객 합계: %{y:,.0f}명"
        "<extra></extra>"
    )
)


fig3.update_layout(
    xaxis_title="날짜",
    yaxis_title="10위권 일관객 합계",
    hovermode="x unified"
)

st.plotly_chart(
    fig3,
    use_container_width=True
)


# --------------------------------------------------
# 가장 관객이 많았던 3일 안내
# --------------------------------------------------
st.markdown("#### 📅 10위권 관객 합계가 가장 많았던 날")

for _, row in (
    top3_days
    .sort_values("일관객", ascending=False)
    .iterrows()
):
    st.write(
        f"{row['날짜'].strftime('%Y-%m-%d')} : "
        f"{int(row['일관객']):,}명"
    )


# --------------------------------------------------
# 그래프 해석
# --------------------------------------------------
st.markdown("#### 💡 이 그래프로 알 수 있는 것")

st.info(
    "여기에 날짜별 10위권 관객 합계의 변화에서 알 수 있는 특징을 "
    "한 문장으로 작성합니다."
)


# ==================================================
# 4구역 : 영화별 일관객 합계 TOP 10
# ==================================================
st.divider()

st.header("4. 영화별 일관객 합계 TOP 10")

st.write(
    "이 기간 동안 영화별 일관객 수를 모두 더해 "
    "관객 합계가 가장 많은 영화 10편을 비교합니다."
)


# --------------------------------------------------
# 영화별 관객 합계와 10위권에 든 날수 계산
# --------------------------------------------------
movie_top10 = (
    df.groupby("영화명")
    .agg(
        관객합계=("일관객", "sum"),
        순위권일수=("날짜", "nunique")
    )
    .reset_index()
)


# --------------------------------------------------
# 관객 합계 상위 10편 선정
# --------------------------------------------------
movie_top10 = (
    movie_top10
    .nlargest(10, "관객합계")
    .sort_values("관객합계", ascending=True)
)


# --------------------------------------------------
# 가로 막대그래프
# --------------------------------------------------
fig4 = px.bar(
    movie_top10,
    x="관객합계",
    y="영화명",
    orientation="h",
    title="영화별 일관객 합계 TOP 10",
    custom_data=["순위권일수"]
)


# --------------------------------------------------
# 마우스를 올렸을 때 보여 줄 정보
# --------------------------------------------------
fig4.update_traces(
    hovertemplate=(
        "영화명: %{y}<br>"
        "일관객 합계: %{x:,.0f}명<br>"
        "10위권에 든 날수: %{customdata[0]}일"
        "<extra></extra>"
    )
)


fig4.update_layout(
    xaxis_title="일관객 합계",
    yaxis_title="영화명",
    showlegend=False
)

st.plotly_chart(
    fig4,
    use_container_width=True
)


# --------------------------------------------------
# 그래프 해석
# --------------------------------------------------
st.markdown("#### 💡 이 그래프로 알 수 있는 것")

st.info(
    "여기에 관객 합계 상위 10편을 비교해 알 수 있는 특징을 "
    "한 문장으로 작성합니다."
)


# ==================================================
# 5구역 : 다음 그래프를 추가할 자리
# ==================================================
st.divider()

st.header("5. 다음 그래프")

st.write(
    "앞으로 새로운 그래프를 추가할 구역입니다."
)
